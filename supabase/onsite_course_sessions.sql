create table if not exists public.onsite_course_sessions (
  id bigint generated by default as identity primary key,
  course_date date not null unique,
  created_at timestamptz not null default now()
);

alter table public.onsite_course_sessions enable row level security;

revoke all on table public.onsite_course_sessions from anon, authenticated;
grant select, delete on table public.onsite_course_sessions to authenticated;
grant insert (course_date) on table public.onsite_course_sessions to authenticated;
grant update (course_date) on table public.onsite_course_sessions to authenticated;
grant usage on sequence public.onsite_course_sessions_id_seq to authenticated;

drop policy if exists "Authenticated users can view onsite course dates"
  on public.onsite_course_sessions;
create policy "Authenticated users can view onsite course dates"
  on public.onsite_course_sessions
  for select
  to authenticated
  using (true);

drop policy if exists "Staff can add onsite course dates"
  on public.onsite_course_sessions;
create policy "Staff can add onsite course dates"
  on public.onsite_course_sessions
  for insert
  to authenticated
  with check (
    exists (
      select 1
      from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role in ('admin', 'superadmin')
    )
  );

drop policy if exists "Staff can update onsite course dates"
  on public.onsite_course_sessions;
create policy "Staff can update onsite course dates"
  on public.onsite_course_sessions
  for update
  to authenticated
  using (
    exists (
      select 1
      from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role in ('admin', 'superadmin')
    )
  )
  with check (
    exists (
      select 1
      from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role in ('admin', 'superadmin')
    )
  );

drop policy if exists "Staff can delete onsite course dates"
  on public.onsite_course_sessions;
create policy "Staff can delete onsite course dates"
  on public.onsite_course_sessions
  for delete
  to authenticated
  using (
    exists (
      select 1
      from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role in ('admin', 'superadmin')
    )
  );

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'onsite_course_sessions'
    )
  then
    alter publication supabase_realtime add table public.onsite_course_sessions;
  end if;
end
$$;
